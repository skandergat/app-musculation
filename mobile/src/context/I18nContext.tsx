function normalizeExerciseName(name: string) {
  return name.trim().replace(/\s+/g, ' ');
}

function exerciseNameForLanguage(name: string, language: Language) {
  const normalized = normalizeExerciseName(name);

  const languageOverride = exerciseLanguageOverrides[language][normalized];
  if (languageOverride) return languageOverride;

  const exactFallback = localizedExerciseFallbacks[language][normalized];
  if (exactFallback) return exactFallback;

  const phrase = [...exercisePhraseTranslations[language], ...exerciseExtraTranslations[language], ...exerciseFinalTranslations[language]].find(
    ([source]) => source.toLocaleLowerCase('fr-FR') === normalized.toLocaleLowerCase('fr-FR')
  );
  if (phrase) return phrase[1];

  // Les noms déjà en anglais/internationaux (JM Press, Muscle-Up, etc.)
  // restent lisibles lorsqu'il n'existe pas de traduction naturelle.
  return normalized;
}

type I18nContextType = {
  language: Language;
  setLanguage: (language: Language) => Promise<void>;
  t: (key: string) => string;
  exerciseName: (name: string) => string;
  muscleGroupName: (name: string) => string;
};

const I18nContext = createContext<I18nContextType | undefined>(undefined);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>('fr');

  useEffect(() => {
    AsyncStorage.getItem(LANGUAGE_KEY).then((value) => {
      if (value === 'fr' || value === 'en' || value === 'ar' || value === 'de') {
        setLanguageState(value);
        I18nManager.allowRTL(true);
        I18nManager.forceRTL(value === 'ar');
      }
    });
  }, []);

  const setLanguage = async (next: Language) => {
    setLanguageState(next);
    await AsyncStorage.setItem(LANGUAGE_KEY, next);
    I18nManager.allowRTL(true);
    I18nManager.forceRTL(next === 'ar');
  };

  const t = (key: string) => translations[language][key] ?? translations.fr[key] ?? key;

  const exerciseName = (name: string) => exerciseNameForLanguage(name, language);
  const muscleGroupName = (name: string) => muscleGroupTranslations[language][name] ?? name;

  return (
    <I18nContext.Provider value={{ language, setLanguage, t, exerciseName, muscleGroupName }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n doit être utilisé dans I18nProvider');
  }
  return context;
}
