import unittest

from db_compat import _replace_qmark_placeholders, _translate_sql


class PostgresTranslationTests(unittest.TestCase):
    def test_qmark_parameters_are_translated_but_quoted_question_marks_are_not(self):
        sql = "SELECT '?' AS literal, name FROM users WHERE id = ? AND email = ?"
        self.assertEqual(
            _replace_qmark_placeholders(sql),
            "SELECT '?' AS literal, name FROM users WHERE id = %s AND email = %s",
        )

    def test_sqlite_autoincrement_becomes_postgres_identity(self):
        sql, params = _translate_sql(
            "CREATE TABLE IF NOT EXISTS users (id INTEGER PRIMARY KEY AUTOINCREMENT, email TEXT)",
            (),
        )
        self.assertIn("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql)
        self.assertNotIn("AUTOINCREMENT", sql)
        self.assertEqual(params, ())

    def test_pragma_table_info_becomes_information_schema_query(self):
        sql, params = _translate_sql("PRAGMA table_info(users)", ())
        self.assertIn("information_schema.columns", sql)
        self.assertIn("column_name AS name", sql)
        self.assertEqual(params, ("users", "users"))

    def test_begin_immediate_becomes_postgres_begin(self):
        sql, params = _translate_sql("BEGIN IMMEDIATE", ())
        self.assertEqual(sql, "BEGIN")
        self.assertEqual(params, ())


if __name__ == "__main__":
    unittest.main()
