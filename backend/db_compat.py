"""Compatibilité de connexion SQLite/PostgreSQL pour le backend LIFTELY.

SQLite reste le moteur par défaut. PostgreSQL est activé uniquement si
LIFTELY_DATABASE_URL est configurée, afin de permettre une migration progressive.
"""
from __future__ import annotations

import os
import re
import sqlite3
from typing import Any

DATABASE_URL = os.getenv("LIFTELY_DATABASE_URL", "").strip()

if DATABASE_URL:
    import psycopg
    from psycopg.rows import tuple_row
    from psycopg.pq import TransactionStatus

    DBIntegrityError = psycopg.IntegrityError
else:
    psycopg = None
    tuple_row = None
    DBIntegrityError = sqlite3.IntegrityError


_AUTO_ID_TABLES = {
    "exercices",
    "users",
    "templates",
    "template_exercices",
    "seances",
    "series",
    "seance_exercices",
}


class HybridRow(dict):
    """Ligne accessible par nom (row['id']) et par index (row[0])."""

    def __init__(self, keys: list[str], values: tuple[Any, ...]):
        super().__init__(zip(keys, values))
        self._values = values

    def __getitem__(self, key):
        if isinstance(key, int):
            return self._values[key]
        return super().__getitem__(key)


def _replace_qmark_placeholders(sql: str) -> str:
    """Convertit les paramètres SQLite ? en %s sans toucher aux chaînes."""
    out: list[str] = []
    quote: str | None = None
    i = 0
    while i < len(sql):
        char = sql[i]
        if quote:
            out.append(char)
            if char == quote:
                if i + 1 < len(sql) and sql[i + 1] == quote:
                    out.append(sql[i + 1])
                    i += 1
                else:
                    quote = None
            elif char == "\\" and quote == "'":
                if i + 1 < len(sql):
                    out.append(sql[i + 1])
                    i += 1
        elif char in ("'", '"'):
            quote = char
            out.append(char)
        elif char == "?":
            out.append("%s")
        else:
            out.append(char)
        i += 1
    return "".join(out)


def _translate_sql(sql: str, params: Any):
    """Traduit les quelques constructions propres à SQLite utilisées par l'app."""
    pragma = re.fullmatch(
        r"\s*PRAGMA\s+table_info\s*\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*\)\s*;?\s*",
        sql,
        re.IGNORECASE,
    )
    if pragma:
        table = pragma.group(1).lower()
        translated = """
            SELECT
                (ordinal_position - 1) AS cid,
                column_name AS name,
                data_type AS type,
                CASE WHEN is_nullable = 'NO' THEN 1 ELSE 0 END AS notnull,
                column_default AS dflt_value,
                CASE WHEN column_name = (
                    SELECT kcu.column_name
                    FROM information_schema.table_constraints tc
                    JOIN information_schema.key_column_usage kcu
                      ON tc.constraint_name = kcu.constraint_name
                     AND tc.table_schema = kcu.table_schema
                    WHERE tc.table_schema = current_schema()
                      AND tc.table_name = %s
                      AND tc.constraint_type = 'PRIMARY KEY'
                    ORDER BY kcu.ordinal_position
                    LIMIT 1
                ) THEN 1 ELSE 0 END AS pk
            FROM information_schema.columns
            WHERE table_schema = current_schema() AND table_name = %s
            ORDER BY ordinal_position
        """
        return translated, (table, table)

    translated = re.sub(r"\bBEGIN\s+IMMEDIATE\b", "BEGIN", sql, flags=re.IGNORECASE)
    translated = re.sub(
        r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b",
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        sql,
        flags=re.IGNORECASE,
    )
    translated = _replace_qmark_placeholders(translated)
    return translated, params


class PostgresCursor:
    def __init__(self, raw_cursor):
        self._cursor = raw_cursor
        self._lastrowid = None

    @property
    def lastrowid(self):
        return self._lastrowid

    @property
    def rowcount(self):
        return self._cursor.rowcount

    @property
    def description(self):
        return self._cursor.description

    def execute(self, sql: str, params: Any = None):
        self._lastrowid = None
        sql = sql.strip()
        params = () if params is None else params

        insert = re.match(r"INSERT\s+INTO\s+([A-Za-z_][A-Za-z0-9_]*)", sql, re.IGNORECASE)
        table = insert.group(1).lower() if insert else None
        has_returning = bool(re.search(r"\bRETURNING\b", sql, re.IGNORECASE))

        if table in _AUTO_ID_TABLES and not has_returning:
            sql = sql.rstrip().rstrip(";") + " RETURNING id"

        translated, translated_params = _translate_sql(sql, params)
        self._cursor.execute(translated, translated_params)

        if table in _AUTO_ID_TABLES and not has_returning:
            row = self._cursor.fetchone()
            if row is not None:
                self._lastrowid = row[0]
        return self

    def fetchone(self):
        row = self._cursor.fetchone()
        if row is None:
            return None
        description = self._cursor.description or ()
        keys = [column.name for column in description]
        return HybridRow(keys, tuple(row))

    def fetchall(self):
        rows = self._cursor.fetchall()
        description = self._cursor.description or ()
        keys = [column.name for column in description]
        return [HybridRow(keys, tuple(row)) for row in rows]

    def close(self):
        self._cursor.close()


class PostgresConnection:
    def __init__(self, raw_connection):
        self._connection = raw_connection

    def execute(self, sql: str, params: Any = None):
        cursor = PostgresCursor(self._connection.cursor())
        return cursor.execute(sql, params)

    def cursor(self):
        return PostgresCursor(self._connection.cursor())

    @property
    def in_transaction(self):
        return self._connection.info.transaction_status != TransactionStatus.IDLE

    def commit(self):
        return self._connection.commit()

    def rollback(self):
        return self._connection.rollback()

    def close(self):
        return self._connection.close()


def get_connection(sqlite_path: str):
    """Ouvre PostgreSQL si LIFTELY_DATABASE_URL est configurée, sinon SQLite."""
    database_url = os.getenv("LIFTELY_DATABASE_URL", "").strip()
    if not database_url:
        conn = sqlite3.connect(sqlite_path, timeout=10)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys = ON")
        conn.execute("PRAGMA busy_timeout = 5000")
        return conn

    if psycopg is None:
        raise RuntimeError(
            "LIFTELY_DATABASE_URL est définie mais psycopg n'est pas installé."
        )

    raw_connection = psycopg.connect(
        database_url,
        connect_timeout=10,
        row_factory=tuple_row,
    )
    return PostgresConnection(raw_connection)
