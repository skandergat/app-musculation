-- LIFTELY PostgreSQL schema.
-- Mirrors the current backend SQLite schema; apply only to a dedicated,
-- empty PostgreSQL schema before importing a validated staging database.
-- The application remains on SQLite until the PostgreSQL adapter is approved.

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    date_creation TEXT NOT NULL,
    email_verified_at TEXT
);

CREATE TABLE IF NOT EXISTS exercices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom TEXT NOT NULL,
    groupe_musculaire TEXT,
    categorie TEXT NOT NULL DEFAULT 'gym',
    actif INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    date_creation TEXT NOT NULL,
    date_expiration TEXT
);

CREATE TABLE IF NOT EXISTS auth_action_tokens (
    token_hash TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    purpose TEXT NOT NULL CHECK (purpose IN ('verify_email', 'password_reset', 'delete_account')),
    date_creation TEXT NOT NULL,
    date_expiration TEXT NOT NULL,
    date_utilisation TEXT
);

CREATE INDEX IF NOT EXISTS idx_auth_action_user_purpose
    ON auth_action_tokens(user_id, purpose, date_expiration);

CREATE TABLE IF NOT EXISTS auth_mail_limits (
    key_hash TEXT PRIMARY KEY,
    window_start TEXT NOT NULL,
    request_count INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS auth_login_limits (
    key_hash TEXT PRIMARY KEY,
    window_start TEXT NOT NULL,
    request_count INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    nom TEXT NOT NULL,
    date_creation TEXT NOT NULL,
    date_modification TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS template_exercices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id BIGINT NOT NULL REFERENCES templates(id) ON DELETE CASCADE,
    exercice_id BIGINT NOT NULL REFERENCES exercices(id),
    position INTEGER NOT NULL DEFAULT 0,
    nombre_series INTEGER NOT NULL DEFAULT 3,
    poids_prevu DOUBLE PRECISION NOT NULL DEFAULT 0,
    repetitions_prevues INTEGER NOT NULL DEFAULT 10,
    UNIQUE(template_id, exercice_id)
);

CREATE INDEX IF NOT EXISTS idx_template_exercices_template
    ON template_exercices(template_id, position);

-- The current SQLite schema stores user_id but does not declare a foreign key.
CREATE TABLE IF NOT EXISTS seances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_debut TEXT NOT NULL,
    date_fin TEXT,
    user_id BIGINT
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_seances_active_user
    ON seances(user_id)
    WHERE date_fin IS NULL AND user_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS series (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seance_id BIGINT NOT NULL REFERENCES seances(id),
    exercice_id BIGINT NOT NULL REFERENCES exercices(id),
    poids DOUBLE PRECISION,
    repetitions INTEGER
);

CREATE TABLE IF NOT EXISTS seance_exercices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seance_id BIGINT NOT NULL REFERENCES seances(id) ON DELETE CASCADE,
    exercice_id BIGINT NOT NULL REFERENCES exercices(id),
    position INTEGER NOT NULL DEFAULT 0,
    date_ajout TEXT NOT NULL,
    nombre_series_prevu INTEGER NOT NULL DEFAULT 1,
    poids_prevu DOUBLE PRECISION NOT NULL DEFAULT 0,
    repetitions_prevues INTEGER NOT NULL DEFAULT 10,
    UNIQUE(seance_id, exercice_id)
);

CREATE INDEX IF NOT EXISTS idx_seance_exercices_seance
    ON seance_exercices(seance_id, position);
